// Generates web/app/tokens-snap.css: every off-scale font-size / font-weight in
// the product CSS and Tailwind classes, re-declared for V2 on the token scale.
const fs = require('fs'), path = require('path')
const WEB = 'C:/Users/jorda/OneDrive/Documents/video-stream/web/'
const FILES = ['app/globals.css', 'app/product.css', 'app/account/account.css', 'app/bounty/bounty.css', 'app/dashboard/campaigns/campaigns.css',
  'app/join/join.css', 'app/how-it-works/how-it-works.css', 'app/roadmap/roadmap.css', 'components/booth/booth.css', 'components/create-room/create-room.css']
const SKIP = /html|:root|\.hm\b|\.hm-|\.mcl-|\.mc-landing|\.ft\b|\.ft-|\.lv\b|\.lv-|mcc-layout-|mcc-stage|overlay|\.fx-|@font|keyframes|\.lab-|\.dev-|\.mcd-|site-tour/
const size = (px) => px <= 12.5 ? 't-1' : px <= 14.5 ? 't-2' : px <= 17 ? 't-3' : px <= 22 ? 't-4' : px <= 32 ? 't-5' : 't-6'
const weight = (w) => (w >= 550 ? 'bold' : 'regular')
const ONSCALE = new Set([12, 14, 16, 20, 28, 44])
const PRE = "html:not([data-style='classic']) "
const NOT = ':where(:not(.mc-landing *, .hm *))'
function parse(css) { // flat list of {media, sel, body}
  css = css.replace(/\/\*[\s\S]*?\*\//g, '')
  const out = []; let i = 0
  const block = (media) => {
    while (i < css.length) {
      const open = css.indexOf('{', i), close = css.indexOf('}', i)
      if (close !== -1 && (open === -1 || close < open)) { i = close + 1; return }
      if (open === -1) { i = css.length; return }
      const prelude = css.slice(i, open).trim(); i = open + 1
      if (prelude.startsWith('@media') || prelude.startsWith('@supports') || prelude.startsWith('@layer')) { block(prelude.startsWith('@media') ? prelude : media); continue }
      if (prelude.startsWith('@')) { let d = 1; while (d && i < css.length) { if (css[i] === '{') d++; else if (css[i] === '}') d--; i++ } continue }
      const end = css.indexOf('}', i); out.push({ media, sel: prelude, body: css.slice(i, end) }); i = end + 1
    }
  }
  block(null); return out
}
const splitTop = (s) => { const out = []; let d = 0, cur = ''; for (const ch of s) { if (ch === '(') d++; if (ch === ')') d--; if (ch === ',' && !d) { out.push(cur); cur = '' } else cur += ch } out.push(cur); return out }
const rules = []; let nSel = 0
for (const f of FILES) {
  for (const r of parse(fs.readFileSync(WEB + f, 'utf8'))) {
    let px = null, w = null
    const fs1 = r.body.match(/(?:^|;)\s*font-size:\s*([\d.]+)px\s*(?:!important)?\s*(?:;|$)/)
    if (fs1) px = +fs1[1]
    const fw = r.body.match(/(?:^|;)\s*font-weight:\s*(\d{3})\s*(?:!important)?\s*(?:;|$)/)
    if (fw) w = +fw[1]
    const sh = r.body.match(/(?:^|;)\s*font:\s*(\d{3})?\s*([\d.]+)px/)
    if (sh) { px = +sh[2]; if (sh[1]) w = +sh[1] }
    const decl = []
    if (px != null && !ONSCALE.has(px) && px >= 8) decl.push(`font-size: var(--${size(px)})`)
    if (w != null && w !== 400 && w !== 700) decl.push(`font-weight: var(--w-${weight(w)})`)
    if (!decl.length) continue
    const sels = splitTop(r.sel).map((s) => s.trim()).filter((s) => s && !SKIP.test(s) && !/::?(-webkit|-moz|placeholder|selection)/.test(s))
    if (!sels.length) continue
    nSel += sels.length
    const sel = sels.map((s) => { const m = s.match(/^(.*?)(::?(?:before|after))$/); return m ? PRE + m[1] + NOT + m[2] : PRE + s + NOT }).join(',\n')
    rules.push({ media: r.media, text: `${sel} { ${decl.join('; ')}; }`, f })
  }
}
// Tailwind classes in the product components
const TW_SIZE = { 'text-lg': 18, 'text-2xl': 24, 'text-3xl': 30, 'text-4xl': 36 }
const TW_W = { 'font-medium': 500, 'font-semibold': 600, 'font-extrabold': 800, 'font-black': 900 }
const tw = new Set()
const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) { if (!/node_modules|\.next|landing|design-system|dev\b/.test(p)) walk(p) } else if (/\.tsx$/.test(e.name)) for (const m of fs.readFileSync(p, 'utf8').matchAll(/(?<![\w:-])(text-\[[\d.]+px\]|font-\[\d{3}\]|text-(?:lg|2xl|3xl|4xl)|font-(?:medium|semibold|extrabold|black))(?![\w-])/g)) tw.add(m[1]) } }
walk(WEB + 'app'); walk(WEB + 'components')
const twRules = []
for (const c of [...tw].sort()) {
  const esc = '.' + c.replace(/([\[\].])/g, (m) => String.fromCharCode(92) + m)
  let d = null
  const ms = c.match(/^text-\[([\d.]+)px\]$/); if (ms && !ONSCALE.has(+ms[1])) d = `font-size: var(--${size(+ms[1])})`
  const mw = c.match(/^font-\[(\d{3})\]$/); if (mw && +mw[1] !== 400 && +mw[1] !== 700) d = `font-weight: var(--w-${weight(+mw[1])})`
  if (TW_SIZE[c]) d = `font-size: var(--${size(TW_SIZE[c])})`
  if (TW_W[c]) d = `font-weight: var(--w-${weight(TW_W[c])})`
  if (d) twRules.push(`${PRE}${esc}${NOT} { ${d}; }`)
}
let out = `/* GENERATED by design-assets/design-pass/gen-snap.cjs — do not hand-edit.
   V2 only. Every product-page rule or Tailwind class that set an off-scale
   font-size or a third/fourth weight, re-declared on the token scale:
   <=12.5px -> --t-1, <=14.5 -> --t-2, <=17 -> --t-3, <=22 -> --t-4,
   <=32 -> --t-5, larger -> --t-6; weights >=550 -> 700, else 400.
   Skipped: the landing, the logo, scaled canvas previews, fluid clamp()
   headings, and rules tokens.css already sets (it loads after this file,
   so its hand-written rules win ties). Classic keeps the source values. */\n\n`
const byMedia = new Map()
for (const r of rules) { const k = r.media || ''; if (!byMedia.has(k)) byMedia.set(k, []); byMedia.get(k).push(r.text) }
for (const [m, list] of byMedia) out += m ? `${m} {\n${list.join('\n')}\n}\n` : list.join('\n') + '\n'
out += '\n/* Tailwind utilities */\n' + twRules.join('\n') + '\n'
fs.writeFileSync(WEB + 'app/tokens-snap.css', out)
console.log('css rules', rules.length, 'selectors', nSel, 'tailwind', twRules.length, 'bytes', out.length)
